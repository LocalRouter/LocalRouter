//! Combined root-CA bundle: the OS's trusted roots plus LocalRouter's proxy CA.
//!
//! Most tools we configure trust an extra CA **additively** — Node's
//! `NODE_EXTRA_CA_CERTS`, Continue's `caBundlePath`, Goose's
//! `GOOSE_CA_CERT_PATH`, Codex's `CODEX_CA_CERTIFICATE`. `SSL_CERT_FILE` and
//! `REQUESTS_CA_BUNDLE` do not: OpenSSL, Python, curl and Go treat the file as
//! the **entire** trust store. Those variables are also inherited by every
//! process the tool starts (an agent's `gh`, `git`, `curl`, `pip`), so pointing
//! one at our root CA alone breaks every host the proxy does not intercept,
//! for the tool and for everything it runs.
//!
//! So those variables point at a bundle that mirrors the OS's own TLS trust
//! (see [`lr_truststore`]: user/admin/system trust settings on macOS, `Root`
//! minus `Disallowed` on Windows, the distribution's compiled bundle on Linux)
//! with our root CA appended. A bundle file cannot defer to the OS at
//! connection time, so [`spawn_refresher`] re-reads the OS store every
//! [`REFRESH_INTERVAL`] and rewrites the file when trust changed: a root the
//! user distrusts, an administrator adds or an OS update removes is reflected
//! for every process started after that.

use std::path::{Path, PathBuf};
use std::time::Duration;

use lr_truststore::DerCerts;

/// How often the OS trust store is re-read while a bundle exists.
pub const REFRESH_INTERVAL: Duration = Duration::from_secs(60);

/// First line of every generated bundle. A file without it predates OS
/// mirroring (or is not ours) and is rebuilt.
const HEADER_FIRST_LINE: &str = "# Generated by LocalRouter.";

const HEADER: &str = "# Generated by LocalRouter.\n\
# The TLS root certificates this computer's operating system trusts, followed\n\
# by LocalRouter's HTTPS inspection proxy CA. Rebuilt automatically whenever the\n\
# OS trust store changes; manual edits are overwritten.\n";

/// Where the generated combined bundle lives.
pub fn combined_bundle_path() -> Result<PathBuf, String> {
    Ok(lr_utils::paths::config_dir()
        .map_err(|e| format!("Failed to resolve config dir: {e}"))?
        .join("proxy")
        .join("combined-ca.pem"))
}

/// Build the bundle text: header, the OS roots, then our CA last.
///
/// Our CA is left out of the OS section if the user also installed it in the
/// OS store, so it appears exactly once. Deterministic for a given input, so
/// an unchanged trust store never rewrites the file.
pub fn compose_bundle(os_roots: &DerCerts, ca_pem: &str) -> Result<String, String> {
    let ours = lr_truststore::parse_pem_certs(ca_pem.as_bytes());
    if ours.is_empty() {
        return Err("The proxy root CA file holds no certificate".into());
    }
    let mut out = String::from(HEADER);
    for der in os_roots.iter().filter(|d| !ours.contains(d)) {
        out.push_str(&lr_truststore::der_to_pem(der));
    }
    for der in &ours {
        out.push_str(&lr_truststore::der_to_pem(der));
    }
    Ok(out)
}

/// Rebuild the bundle at `out_path` from `os_roots` and the CA at
/// `ca_cert_path`. Returns whether the file changed.
///
/// When the OS store cannot be read the existing file is kept as it is:
/// writing a partial bundle would narrow the trust of every tool pointed at
/// it, and an out-of-date one is the lesser harm.
pub fn refresh_bundle_at(
    out_path: &Path,
    ca_cert_path: &Path,
    os_roots: impl FnOnce() -> Result<DerCerts, String>,
) -> Result<bool, String> {
    let ca_pem = std::fs::read_to_string(ca_cert_path)
        .map_err(|e| format!("Failed to read root CA {}: {e}", ca_cert_path.display()))?;
    let bundle = compose_bundle(&os_roots()?, &ca_pem)?;
    if std::fs::read_to_string(out_path).is_ok_and(|existing| existing == bundle) {
        return Ok(false);
    }
    write_atomically(out_path, bundle.as_bytes())?;
    Ok(true)
}

/// Replace `path` in one step, so a tool starting mid-refresh reads either the
/// old bundle or the new one, never half of one.
fn write_atomically(path: &Path, bytes: &[u8]) -> Result<(), String> {
    let parent = path
        .parent()
        .ok_or_else(|| format!("{} has no parent directory", path.display()))?;
    std::fs::create_dir_all(parent)
        .map_err(|e| format!("Failed to create {}: {e}", parent.display()))?;
    let tmp = parent.join(format!(
        ".{}.tmp-{}",
        path.file_name()
            .and_then(|n| n.to_str())
            .unwrap_or("bundle"),
        std::process::id()
    ));
    std::fs::write(&tmp, bytes).map_err(|e| format!("Failed to write {}: {e}", tmp.display()))?;
    if let Err(rename_err) = std::fs::rename(&tmp, path) {
        // Windows refuses to replace a file another process holds open
        // without delete sharing; overwrite in place instead.
        let _ = std::fs::remove_file(&tmp);
        std::fs::write(path, bytes)
            .map_err(|e| format!("Failed to replace {} ({rename_err}): {e}", path.display()))?;
    }
    Ok(())
}

/// Whether `content` is a generated bundle that already carries our CA.
fn is_current_format_with_ca(content: &str, ca_pem: &str) -> bool {
    let ours = lr_truststore::parse_pem_certs(ca_pem.as_bytes());
    if ours.is_empty() || !content.starts_with(HEADER_FIRST_LINE) {
        return false;
    }
    let present = lr_truststore::parse_pem_certs(content.as_bytes());
    ours.iter().all(|c| present.contains(c))
}

/// Make sure the bundle exists for a tool about to be pointed at it, and
/// return its path.
///
/// An existing generated bundle that carries our CA is returned as is (the
/// refresher keeps it in step with the OS), so the setup UI can call this on
/// every render. Anything else is rebuilt from the OS store now.
pub fn ensure_combined_bundle(ca_cert_path: &Path) -> Result<PathBuf, String> {
    let out_path = combined_bundle_path()?;
    let ca_pem = std::fs::read_to_string(ca_cert_path)
        .map_err(|e| format!("Failed to read root CA {}: {e}", ca_cert_path.display()))?;
    if std::fs::read_to_string(&out_path).is_ok_and(|c| is_current_format_with_ca(&c, &ca_pem)) {
        return Ok(out_path);
    }
    refresh_bundle_at(&out_path, ca_cert_path, lr_truststore::os_trusted_roots)?;
    Ok(out_path)
}

/// Keep the bundle in step with the OS trust store for as long as the app
/// runs. Only an existing bundle is maintained — one is created the first
/// time a tool is set up to use it — so the OS store is not polled for users
/// who never need one. The first pass runs immediately, which also upgrades a
/// bundle written by an older version.
pub fn spawn_refresher(ca_cert_path: PathBuf) {
    tokio::spawn(async move {
        loop {
            if let Ok(out_path) = combined_bundle_path() {
                if out_path.exists() {
                    let ca = ca_cert_path.clone();
                    let result = tokio::task::spawn_blocking(move || {
                        refresh_bundle_at(&out_path, &ca, lr_truststore::os_trusted_roots)
                    })
                    .await;
                    match result {
                        Ok(Ok(true)) => tracing::info!(
                            "Rebuilt the combined CA bundle to match the OS trust store"
                        ),
                        Ok(Ok(false)) => {}
                        Ok(Err(e)) => tracing::warn!(
                            "Could not refresh the combined CA bundle (keeping the current one): {e}"
                        ),
                        Err(e) => tracing::warn!("Combined CA bundle refresh panicked: {e}"),
                    }
                }
            }
            tokio::time::sleep(REFRESH_INTERVAL).await;
        }
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ca_pem() -> String {
        lr_truststore::der_to_pem(&[0xCA, 0xCA])
    }

    fn roots(ders: &[&[u8]]) -> DerCerts {
        lr_truststore::normalize(ders.iter().map(|d| d.to_vec()).collect())
    }

    #[test]
    fn bundle_holds_the_os_roots_then_our_ca() {
        let out = compose_bundle(&roots(&[&[1], &[2]]), &ca_pem()).unwrap();
        assert!(out.starts_with(HEADER_FIRST_LINE));
        let certs = lr_truststore::parse_pem_certs(out.as_bytes());
        assert_eq!(certs, vec![vec![1], vec![2], vec![0xCA, 0xCA]]);
    }

    #[test]
    fn our_ca_appears_once_when_the_os_trusts_it_too() {
        let out = compose_bundle(&roots(&[&[1], &[0xCA, 0xCA]]), &ca_pem()).unwrap();
        let certs = lr_truststore::parse_pem_certs(out.as_bytes());
        assert_eq!(certs, vec![vec![1], vec![0xCA, 0xCA]]);
    }

    #[test]
    fn a_ca_file_without_a_certificate_is_an_error() {
        assert!(compose_bundle(&roots(&[&[1]]), "not a pem").is_err());
    }

    fn setup() -> (tempfile::TempDir, PathBuf, PathBuf) {
        let dir = tempfile::tempdir().unwrap();
        let ca = dir.path().join("root-ca.pem");
        std::fs::write(&ca, ca_pem()).unwrap();
        let out = dir.path().join("proxy").join("combined-ca.pem");
        (dir, ca, out)
    }

    #[test]
    fn refresh_writes_then_rewrites_only_when_trust_changes() {
        let (_dir, ca, out) = setup();
        assert!(refresh_bundle_at(&out, &ca, || Ok(roots(&[&[1], &[2]]))).unwrap());
        assert!(!refresh_bundle_at(&out, &ca, || Ok(roots(&[&[2], &[1]]))).unwrap());

        // The OS distrusts root 1: it disappears from the bundle.
        assert!(refresh_bundle_at(&out, &ca, || Ok(roots(&[&[2]]))).unwrap());
        let certs = lr_truststore::parse_pem_certs(&std::fs::read(&out).unwrap());
        assert_eq!(certs, vec![vec![2], vec![0xCA, 0xCA]]);

        // A root is added (an administrator trusts a corporate CA).
        assert!(refresh_bundle_at(&out, &ca, || Ok(roots(&[&[2], &[3]]))).unwrap());
        let certs = lr_truststore::parse_pem_certs(&std::fs::read(&out).unwrap());
        assert_eq!(certs, vec![vec![2], vec![3], vec![0xCA, 0xCA]]);
    }

    #[test]
    fn an_unreadable_os_store_keeps_the_existing_bundle() {
        let (_dir, ca, out) = setup();
        refresh_bundle_at(&out, &ca, || Ok(roots(&[&[1]]))).unwrap();
        let before = std::fs::read(&out).unwrap();
        assert!(refresh_bundle_at(&out, &ca, || Err("denied".into())).is_err());
        assert_eq!(std::fs::read(&out).unwrap(), before);
    }

    #[test]
    fn no_temporary_file_is_left_behind() {
        let (_dir, ca, out) = setup();
        refresh_bundle_at(&out, &ca, || Ok(roots(&[&[1]]))).unwrap();
        let names: Vec<_> = std::fs::read_dir(out.parent().unwrap())
            .unwrap()
            .map(|e| e.unwrap().file_name())
            .collect();
        assert_eq!(names, vec![std::ffi::OsString::from("combined-ca.pem")]);
    }

    #[test]
    fn only_a_generated_bundle_with_our_ca_counts_as_current() {
        let ca = ca_pem();
        let current = compose_bundle(&roots(&[&[1]]), &ca).unwrap();
        assert!(is_current_format_with_ca(&current, &ca));

        // An older certifi-based bundle (no header) is rebuilt.
        let legacy = format!("{}{ca}", lr_truststore::der_to_pem(&[1]));
        assert!(!is_current_format_with_ca(&legacy, &ca));

        // A bundle generated for a since-regenerated CA is rebuilt.
        let other = lr_truststore::der_to_pem(&[0xDE, 0xAD]);
        assert!(!is_current_format_with_ca(&current, &other));
    }
}

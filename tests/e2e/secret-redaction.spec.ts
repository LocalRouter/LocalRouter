test('large event renders bounded sections, keeps decisions responsive and preserves reveal privacy', async ({ page }) => {
  await page.goto('/__preview/secret-redaction?large')
  const popup = page.getByTestId('approval-popup')
  const request = popup.getByLabel('Complete request JSON')
  const sections = popup.getByLabel('Request sections')
  await expect(sections).toContainText('of 10,')
  expect(await request.evaluate(node => node.textContent!.length)).toBeLessThan(17_000)
  await expect(request.locator('mark')).toBeInViewport()
  await expect(popup.getByRole('button', { name: 'Block', exact: true })).toBeInViewport()
  await popup.getByRole('button', { name: 'Reveal secret', exact: true }).click()
  await expect(request.locator('mark')).toHaveText(SECRET)
  await popup.getByRole('button', { name: 'Hide secret', exact: true }).click()
  await expect(request).not.toContainText(SECRET)
  const initialRange = await sections.textContent()
  await sections.getByRole('button', { name: 'Earlier section' }).click()
  await expect(request.locator('mark')).toHaveCount(0)
  expect(await sections.textContent()).not.toEqual(initialRange)
  await sections.getByRole('button', { name: 'Later section' }).click()
  await expect(request.locator('mark')).toBeInViewport()
  expect(await sections.textContent()).toEqual(initialRange)
  for (let i = 0; i < 4; i++) await sections.getByRole('button', { name: 'Later section' }).click()
  expect(await request.evaluate(node => node.textContent!.length)).toBeLessThanOrEqual(16_000)
  await sections.getByRole('button', { name: 'Jump to secret' }).click()
  await expect(request.locator('mark')).toBeInViewport()
  await popup.getByRole('button', { name: 'Block', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Request blocked')
  await expect(page.getByTestId('outgoing-payload')).toHaveText('Not forwarded')
})


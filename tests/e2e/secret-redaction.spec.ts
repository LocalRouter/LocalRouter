test('editing a large argument section preserves content before and after it', async ({ page }) => {
  await page.goto('/__preview/secret-redaction?kind=editor')
  const popup = page.getByTestId('large-popup')
  await popup.getByRole('button', { name: 'Modify', exact: true }).click()
  const argument = popup.locator('div[aria-label="message"]')
  await expect(argument.locator('textarea')).toHaveValue(/Long payload/)
  expect((await argument.locator('textarea').inputValue()).length).toBe(16_000)
  await argument.getByRole('button', { name: 'Later section' }).click()
  const original = await argument.locator('textarea').inputValue()
  await argument.locator('textarea').fill('EDIT' + original)
  await argument.getByRole('button', { name: 'Earlier section' }).click()
  await expect(argument.locator('textarea')).toHaveValue(/^Long payload/)
  await popup.getByRole('button', { name: 'Allow with Edits', exact: true }).click()
  await expect(page.getByTestId('popup-action')).toHaveText('submitted')
  const submitted = JSON.parse(await page.getByTestId('submitted-fields').innerText())
  expect(submitted.message.length).toBe(10_500_004)
  expect(submitted.message.section).toMatch(/^EDIT/)
  expect(submitted.message.beginning).toMatch(/^Long payload/)
  expect(submitted.message.end).toMatch(/words\. $/)
  expect(submitted.untouched).toBe('keep me')
})
